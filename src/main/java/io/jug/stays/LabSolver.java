package io.jug.stays;

import org.bson.Document;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * "Solve it for me": writes the reference solution of an exercise into your source file,
 * between its markers, so you can read it in your editor. The running app picks it up
 * after a rebuild: automatically with {@code docker compose watch}, otherwise restart it.
 *
 * The reference code ships in src/main/resources/labs/solutions.json, generated by
 * tools/make_starter.py from the solution branch.
 */
public final class LabSolver {

    private static final Pattern START = Pattern.compile("^(\\s*)// ▶ LAB (\\S+)\\s*$");
    private static final Pattern END = Pattern.compile("^\\s*// ◀ LAB (\\S+)\\s*$");

    private final Path sourceRoot;
    private final boolean enabled;
    private final String runtime;
    private final Document solutions;

    public LabSolver(Config config) {
        this.sourceRoot = Path.of(config.get("SOURCE_DIR", "src/main/java")).toAbsolutePath().normalize();
        this.enabled = !config.get("LAB_SOLVER", "true").equalsIgnoreCase("false");
        this.runtime = config.get("STAYS_RUNTIME", "local");
        this.solutions = load();
    }

    private static Document load() {
        try (InputStream in = LabSolver.class.getResourceAsStream("/labs/solutions.json")) {
            return in == null ? new Document() : Document.parse(new String(in.readAllBytes(), StandardCharsets.UTF_8));
        } catch (IOException e) {
            return new Document();
        }
    }

    /** Can this app write solutions? Needs the bundled solutions and a writable source folder. */
    public boolean available() {
        return enabled && !solutions.isEmpty() && Files.isDirectory(sourceRoot);
    }

    /** The before/after viewer only needs the bundled solutions. */
    public boolean hasSolutions() {
        return !solutions.isEmpty();
    }

    /** What the source file says right now: "todo" (still the throw), "written" (any code), or "unknown". */
    public String sourceState(String id) {
        try {
            for (Block b : blocks(id)) {
                String body = String.join("\n", b.lines.subList(b.start + 1, b.end)).trim();
                if (body.equals("throw Lab.todo(\"" + id + "\");")) return "todo";
            }
            return "written";
        } catch (RuntimeException | IOException e) {
            return "unknown";
        }
    }

    /**
     * Solve one exercise. Labs build on each other, so this only works when every earlier
     * exercise has code in it (yours or the reference). With {@code through}, it first
     * solves the earlier exercises that are still to do: "catch me up to here".
     */
    public Document solve(String id, boolean through) {
        if (!Lab.EXERCISES.containsKey(id)) return error("Unknown exercise " + id);
        if (!"todo".equals(sourceState(id))) return error("Lab " + id + " already has code in it.");
        List<String> solved = new ArrayList<>();
        for (Lab.Exercise e : Lab.all()) {
            if (e.id().equals(id)) break;
            if (!"todo".equals(sourceState(e.id()))) continue;
            if (!through) return error("Do Lab " + e.id() + " first: " + e.title() + ". Labs go in order.");
            Document r = rewrite(e.id(), true);
            if (!Boolean.TRUE.equals(r.getBoolean("ok"))) return r;
            solved.add(e.id());
        }
        Document r = rewrite(id, true);
        solved.add(id);
        return Boolean.TRUE.equals(r.getBoolean("ok")) ? r.append("solved", solved) : r;
    }

    /** Put the TODO back. Newest first: an exercise can only be reset when nothing after it has code. */
    public Document reset(String id) {
        if (!Lab.EXERCISES.containsKey(id)) return error("Unknown exercise " + id);
        boolean after = false;
        String newest = null;
        for (Lab.Exercise e : Lab.all()) {
            if (after && "written".equals(sourceState(e.id()))) newest = e.id();
            if (e.id().equals(id)) after = true;
        }
        if (newest != null) return error("Undo Lab " + newest + " first. Labs are undone newest first.");
        return rewrite(id, false);
    }

    /**
     * Before / after for the code viewer: the method as the starter has it, the method with the
     * reference solution, and (when the source folder is reachable) the method as it is in your file now.
     * Works without a source folder too, from the bundled solutions alone.
     */
    public Document code(String id) {
        Lab.Exercise e = Lab.EXERCISES.get(id);
        if (e == null) return error("Unknown exercise " + id);
        List<?> code = solutions.getList(id, Object.class);
        if (code == null || code.isEmpty()) return error("No reference solution bundled for " + id);
        List<List<String>> current = null;
        if (Files.isDirectory(sourceRoot)) {
            try {
                current = new ArrayList<>();
                for (Block b : blocks(id)) current.add(new ArrayList<>(b.lines.subList(b.start, b.end + 1)));
                if (current.isEmpty()) current = null;
            } catch (RuntimeException | IOException ignored) {
                current = null;
            }
        }
        List<Document> parts = new ArrayList<>();
        for (int i = 0; i < code.size(); i++) {
            Document part = (Document) code.get(i);
            String indent = part.getString("indent");
            String closing = indent.length() >= 4 ? indent.substring(4) + "}" : "}";
            List<String> header = part.getList("header", String.class, List.of());
            List<String> before = new ArrayList<>(header);
            before.add(indent + "// ▶ LAB " + id);
            before.add(indent + "throw Lab.todo(\"" + id + "\");");
            before.add(indent + "// ◀ LAB " + id);
            before.add(closing);
            List<String> after = new ArrayList<>(header);
            after.add(indent + "// ▶ LAB " + id);
            after.addAll(part.getList("lines", String.class));
            after.add(indent + "// ◀ LAB " + id);
            after.add(closing);
            Document d = new Document("file", part.getString("file"))
                    .append("headerLines", header.size())
                    .append("before", before)
                    .append("after", after);
            if (current != null && i < current.size()) {
                List<String> mine = new ArrayList<>(header);
                mine.addAll(current.get(i));
                mine.add(closing);
                d.append("current", mine);
            }
            parts.add(d);
        }
        return new Document("ok", true).append("id", id).append("title", e.title()).append("where", e.where())
                .append("hint", e.hint()).append("parts", parts).append("state", sourceState(id));
    }

    /** Every exercise back to TODO: for the instructor's demo machine. */
    public Document resetAll() {
        List<Lab.Exercise> all = new ArrayList<>(Lab.all());
        java.util.Collections.reverse(all);
        Document last = error("Nothing to reset");
        for (Lab.Exercise e : all) {
            if (!"written".equals(sourceState(e.id()))) continue;
            last = rewrite(e.id(), false);
            if (!Boolean.TRUE.equals(last.getBoolean("ok"))) return last;
        }
        return last;
    }

    private Document rewrite(String id, boolean solve) {
        if (!enabled) return error("The solve button is turned off on this server (LAB_SOLVER=false).");
        if (!Lab.EXERCISES.containsKey(id)) return error("Unknown exercise " + id);
        List<?> code = solutions.getList(id, Object.class);
        if (solve && (code == null || code.isEmpty())) return error("No reference solution bundled for " + id);
        if (!Files.isDirectory(sourceRoot)) {
            return error("Source folder not found: " + sourceRoot + ". Run the app from the repository root"
                    + " (with Docker, the compose file mounts ./src for this).");
        }
        try {
            List<Block> blocks = blocks(id);
            if (blocks.isEmpty()) return error("Markers for LAB " + id + " not found in " + fileOf(id));
            // Edit from the bottom up so earlier line numbers stay valid.
            Path file = blocks.get(0).file;
            List<String> lines = blocks.get(0).lines;
            for (int i = blocks.size() - 1; i >= 0; i--) {
                Block b = blocks.get(i);
                List<String> replacement = new ArrayList<>();
                if (solve) {
                    Document part = (Document) code.get(Math.min(i, code.size() - 1));
                    replacement.addAll(part.getList("lines", String.class));
                } else {
                    replacement.add(b.indent + "throw Lab.todo(\"" + id + "\");");
                }
                for (int k = b.end - 1; k > b.start; k--) lines.remove(k);
                lines.addAll(b.start + 1, replacement);
            }
            Files.writeString(file, String.join("\n", lines) + "\n", StandardCharsets.UTF_8);
            String next = runtime.equals("docker")
                    ? "If docker compose watch is running, the app rebuilds and restarts now. Otherwise run docker compose up --build."
                    : "Restart the app to use it (Ctrl+C, then mvn -q compile exec:java).";
            return new Document("ok", true).append("id", id).append("file", sourceRoot.relativize(file).toString())
                    .append("action", solve ? "solved" : "reset").append("next", next);
        } catch (IOException e) {
            return error("Could not write " + fileOf(id) + ": " + e.getMessage()
                    + (runtime.equals("docker") ? " (on Linux, run compose with your user id: UID=$(id -u) docker compose watch)" : ""));
        }
    }

    private record Block(Path file, List<String> lines, int start, int end, String indent) {}

    /** Every marker pair for an exercise, in file order. All blocks of one exercise live in one file. */
    private List<Block> blocks(String id) throws IOException {
        Path file = fileOf(id);
        List<String> lines = new ArrayList<>(Files.readAllLines(file, StandardCharsets.UTF_8));
        List<Block> out = new ArrayList<>();
        for (int i = 0; i < lines.size(); i++) {
            Matcher m = START.matcher(lines.get(i));
            if (!m.matches() || !m.group(2).equals(id)) continue;
            int j = i + 1;
            while (j < lines.size() && !END.matcher(lines.get(j)).matches()) j++;
            if (j == lines.size()) throw new IllegalStateException("LAB " + id + " has no end marker in " + file);
            out.add(new Block(file, lines, i, j, m.group(1)));
            i = j;
        }
        return out;
    }

    private Path fileOf(String id) {
        List<?> code = solutions.getList(id, Object.class);
        String rel = code == null || code.isEmpty() ? null : ((Document) code.get(0)).getString("file");
        if (rel == null) throw new IllegalStateException("No bundled solution for LAB " + id);
        Path p = sourceRoot.resolve(rel).normalize();
        if (!p.startsWith(sourceRoot)) throw new IllegalStateException("Refusing to write outside " + sourceRoot);
        return p;
    }

    private static Document error(String message) {
        return new Document("ok", false).append("error", message);
    }
}
